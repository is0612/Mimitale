// ============================================================================
//  data/narration.js —— 叙述模式 / 推进节奏 / GM 主持规则
//
//  这三样都只是「改变模型看世界的视角」：最终拼成一段系统提示词，
//  中间没有逻辑，也不依赖别的模块。纯字符串、不碰 DOM —— 调文案改这里即可。
//
//  节奏文案里的花括号是场景占位符，由 paceRuleText 按 isGm 替换：
//      {who}               轮到谁动：GM=NPC / 单角色=你
//      {step2}             第二步写什么：GM=在场 NPC 各一句 / 单角色=你给一句
//      {multi}             GM 专属：「NPC 之间的分工由你安排」（整行）
//      {multiInline}       GM 专属：同一句的内联版（单角色下整行为空，不留空行）
//      {standoffRule}      step 里的「别替玩家了结对峙」
//      {standoffBrisk}     brisk 里的对应段落
//      {moveDefault}       step 里的「拿不准该谁动」
//      {moveDefaultInline} brisk 里的内联版
//      {noSelfIntro}       GM 专属：「已出场的 NPC 别自己凑过来」
//
//  ⚠️ 新增占位符要同步登记到 paceRuleText 的 vars 里，漏了会原样发给模型
//     （smoke-renderer.js 有「没有没替换掉的占位符」的断言）。
// ============================================================================

const hasOwn = (obj, key) => Object.prototype.hasOwnProperty.call(obj, key);

/** 从档位表里取合法值，查不到（或传进来 undefined）就回落到默认档 */
function pickMode(modes, mode, fallback) {
  return typeof mode === 'string' && hasOwn(modes, mode) ? mode : fallback;
}

