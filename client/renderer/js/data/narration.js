/**
 * 把节奏文案里的场景占位符换成具体的词。
 *
 * 世界模式（isGm）说「NPC」；单角色模式用第二人称「你」—— 这套规则通篇的「你」
 * 都指模型要演的那个角色（见 roleplayRuleText 开头的「你现在要扮演…」）。
 *
 * ⚠️ 单角色模式下别点名角色，也别出现「NPC」或「你替 TA」：
 *    前者会和「你」打架，后者是自我指涉，还会怂恿模型凭空造人。
 *    下面这些整段占位符就是为两种模式共用一份文案准备的。
 */
function paceRuleText(convo, isGm) {
  const mode = PACE_MODES[convoPaceMode(convo)];
  const who = isGm ? 'NPC' : '你';

  // 单角色没有「多个 NPC 之间分工」这回事 —— multi / multiInline / noSelfIntro
  // 在那边都是空串；multiInline 带换行，空串直接消失，不会留下只有缩进的孤行。
  const vars = {
    who,
    step2: isGm ? '在场 NPC 各给一句话或一个动作（每人最多一次）' : '你给一句话或一个动作（最多一次）',
    multi: isGm ? '  · NPC 之间的先后、分工、争执 —— 由你安排，不要抛给玩家决定\n' : '',
    multiInline: isGm ? '   NPC 之间的先后和分工由你安排，不要抛给玩家决定；\n' : '',
    standoffRule: isGm
      ? '  · 不要在对峙里替玩家了结：不让对手突然离场或摊牌，\n' +
        '    不让别的 NPC 接管玩家正在进行的互动\n'
      : '  · 不要替玩家了结冲突：不让对方突然离场或摊牌，不替玩家化解冲突\n',
    standoffBrisk: isGm
      ? ' · 在对峙里不要替玩家把局面解决掉：不让对手突然离场或摊牌，\n' +
        '   不让别的 NPC 走过来接管玩家正在进行的互动，不替玩家化解冲突；\n'
      : ' · 不要替玩家把冲突解决掉：不让对方突然离场或摊牌，不替玩家化解冲突；\n',
    moveDefault: isGm
      ? '  · 拿不准该谁动时，默认由 NPC 动 —— 某个 NPC 想干什么、想要什么、\n' +
        '    先做什么，那是你的事，你替他们拿主意，别丢回给玩家。\n'
      : '  · 拿不准接下来该谁动时，默认由你先动 —— 你想干什么、想要什么、\n' +
        '    先做什么，那是你的事，别丢回给玩家。\n',
    moveDefaultInline: isGm
      ? '默认由 NPC 动 —— 某个 NPC 想干什么，你替他们拿主意'
      : '默认由你先动 —— 你想干什么，自己拿主意',
    noSelfIntro: isGm ? '，已出场的 NPC 也不要自己凑过来改变局面' : ''
  };

  // 函数式替换：值里带 $ 也不会被当成 $& / $1 这类特殊序列；
  // 没登记的占位符原样保留，smoke 的「没有没替换掉的占位符」会抓到。
  const out = mode.text.replace(/\{(\w+)\}/g, (raw, key) => (hasOwn(vars, key) ? vars[key] : raw));

  // 调用方紧接着拼下一段（【标重点】/「不要提到自己是 AI」），
  // 末尾漏一个 \n 两段就会粘成一行。在文案里很难一眼看出来，这里统一兜住。
  return out.endsWith('\n') ? out : `${out}\n`;
}

