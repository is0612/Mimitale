// ============================================================================
//  smoke-groups.js —— 把 122 个场景按功能域切开，配合 --group=<域> 只跑一块
//
//  为什么需要它：整套要 35 秒左右，改一行聊天代码也得等全场跑完。
//  --only 本来就能筛场景，但场景之间有**累积依赖**（后面的场景蹭前面造出来的
//  会话 / 角色 / 世界书），单筛出来的那批会一片红。
//  所以分组跑还得配夹具：smoke-seed-<域名>.json，跑这一域之前先灌进假后端。
//
//  用法：
//    npm run smoke:group -- chat          跑「聊天与消息」域
//    npm run smoke:group -- list          列出所有域和场景数
//
//  ⚠️ 场景名必须和 smoke-renderer.js 里 await scenario('...') 一字不差。
//     改了场景名这里要跟着改 —— --group 会核对并在对不上时报红，不会静默少跑。
//
//  ⚠️ 域的边界是照着**依赖**切的，不是照着目录切的。
//     一个域要能独立跑绿，它需要的会话 / 角色 / 世界书必须由域内场景自己造出来
//     或者由夹具带进来。所以「角色卡」和「世界书」合成了一个 library 域 ——
//     世界书的场景要蹭角色卡场景存下来的卡，拆开就红。
//     同理「外观：聊天区那几样 / 侧栏 / 简化右栏」归到 chat：它们断言的是
//     「有消息的会话长什么样」，塞进外壳域只会天天红。
//
//  ⚠️ 夹具是自动拍的，别手改：
//    electron tools/smoke-test.js --dump-groups
//  跑整套时趁每个域第一个场景刚要开始，把假后端状态存成 smoke-seed-<域名>.json。
//  场景改名、加场景、改域边界之后都要重拍一次，否则夹具和域对不上。
// ============================================================================

